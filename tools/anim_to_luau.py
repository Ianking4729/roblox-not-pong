"""Convert /animate (fwjelaa kit) JSON exports into src/shared/Shared/NotPongAnimData.luau.

    python tools/anim_to_luau.py <pack out dir> NP_DiveRight NP_DiveLeft NP_ShuffleRight ...

The game builds KeyframeSequences from this data at runtime (Shared/NotPongAnims), exactly like the generated stance,
so nothing is uploaded or published. Pose CFrames are the kit's Roblox joint transforms for the block R15 rig;
NotPongAnims rescales the LowerTorso translation per avatar.
"""
import json
import os
import sys

STYLES = ["Linear", "Constant", "CubicV2", "Elastic", "Bounce", "Cubic"]
DIRS = ["In", "Out", "InOut"]


def num(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def convert(path):
    d = json.load(open(path))
    joints = list(d["parents"].keys())
    lines = [f'\t{d["name"]} = {{', f'\t\tlength = {num(d["length"] / d["fps"])},',
             f'\t\tloop = {"true" if d["loop"] else "false"},', f'\t\tpriority = "{d["priority"]}",',
             "\t\tparents = {" + ", ".join(f'{j} = "{p}"' for j, p in d["parents"].items()) + "},",
             "\t\tjoints = {" + ", ".join(f'"{j}"' for j in joints) + "},"]
    markers = []
    for k in d["keyframes"]:
        for m in k.get("markers") or []:
            markers.append(f'{{"{m[0]}", {num(k["time"])}}}')
    lines.append("\t\tmarkers = {" + ", ".join(markers) + "},")
    lines.append("\t\t-- keyframes: { time, { [joint index] = { x, y, z, r00..r22, style, direction } } }")
    lines.append("\t\tkeyframes = {")
    for k in d["keyframes"]:
        parts = []
        for j, pose in k["poses"].items():
            cf = ", ".join(num(v) for v in pose["cf"])
            parts.append(f'[{joints.index(j) + 1}] = {{{cf}, {STYLES.index(pose["style"]) + 1}, {DIRS.index(pose["dir"]) + 1}}}')
        lines.append(f'\t\t\t{{{num(k["time"])}, {{{", ".join(parts)}}}}},')
    lines.append("\t\t},")
    lines.append("\t},")
    return lines


def main():
    out_dir, names = sys.argv[1], sys.argv[2:]
    body = ["--!nocheck", "-- GENERATED by tools/anim_to_luau.py from the /animate kit exports (anims/_notpong.py in the kit).",
            "-- Do not edit by hand: change the recipe, re-export, regenerate. Method by fwjelaa (FWJ STUDIOS).",
            f'-- STYLES = {STYLES}, DIRS = {DIRS} (1-based indices below)', "", "return {"]
    for n in names:
        body += convert(os.path.join(out_dir, n + ".json"))
    body.append("}")
    target = os.path.join(os.path.dirname(__file__), "..", "src", "shared", "Shared", "NotPongAnimData.luau")
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(body) + "\n")
    print("wrote", os.path.abspath(target), os.path.getsize(target), "bytes")


if __name__ == "__main__":
    main()
